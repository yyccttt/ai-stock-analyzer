export function detectLanguage() {
  try {
    const saved = window.localStorage.getItem(LANGUAGE_KEY);
    if (SUPPORTED_LANGUAGES.includes(saved)) return saved;
  } catch {
    // Fall through to the browser language.
  }
  return window.navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function saveLanguage(language) {
  if (!SUPPORTED_LANGUAGES.includes(language)) return;
  try {
    window.localStorage.setItem(LANGUAGE_KEY, language);
  } catch {
    // Language switching still works when local storage is unavailable.
  }
}

export function getErrorMessage(error, copy) {
  if (error?.code && copy.errors[error.code]) return copy.errors[error.code];
  if (error?.code === 'REQUEST_TIMEOUT') return copy.errors.requestTimeout;
  return error?.message || copy.errors.unknown;
}
